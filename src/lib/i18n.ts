export interface Translator {
  t: (key: string, vars?: Record<string, string | number>) => string;
  d: (text: string) => string;
  dir: 'rtl' | 'ltr';
  language: 'fa' | 'en';
  textMode: Preferences['textMode'];
}

function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function createTranslator(preferences: Preferences): Translator {
  const language = preferences.uiLanguage;
  const mode = preferences.textMode;
  const dir = language === 'fa' && mode === 'native' ? 'rtl' : 'ltr';
  return {
    language,
    textMode: mode,
    dir,
    t: (key, vars) => {
      const source = language === 'en' ? en[key] ?? fa[key] ?? key : fa[key] ?? en[key] ?? key;
      const selected = mode === 'latin' ? en[key] ?? source : source;
      return interpolate(applyTextMode(selected, mode), vars);
    },
    d: (text) => {
      if (mode === 'native') return text;
      if (mode === 'latin') return applyTextMode(en[text] ?? text, 'latin');
      return applyTextMode(text, mode);
    },
  };
}

export function translateKey(key: string, language: 'fa' | 'en', mode: Preferences['textMode']): string {
  const source = language === 'en' ? en[key] ?? fa[key] ?? key : fa[key] ?? en[key] ?? key;
  const selected = mode === 'latin' ? en[key] ?? source : source;
  return applyTextMode(selected, mode);
}
